function metrics = make_paper_metrics(runRows,halfWidths)
%MAKE_PAPER_METRICS Paired objective and cost statistics for paper plots.

metrics = table();
for halfWidth = halfWidths
    pso = sortrows(runRows(runRows.HalfWidthDeg == halfWidth & ...
        runRows.Algorithm == "particleswarm",:),'Seed');
    hybrid = sortrows(runRows(runRows.HalfWidthDeg == halfWidth & ...
        runRows.Algorithm == "PSO+fmincon",:),'Seed');
    reduction = 100*(pso.FunctionEvaluations-hybrid.FunctionEvaluations)./ ...
        pso.FunctionEvaluations;
    objectiveImprovement = 100*(pso.Objective-hybrid.Objective)./pso.Objective;
    objectiveDifference = abs(objectiveImprovement);
    if exist('signrank','file') == 2
        pValue = signrank(hybrid.Objective,pso.Objective);
    else
        pValue = NaN;
    end
    improvementMedian = median(objectiveImprovement);
    reductionMedian = median(reduction);
    equivalentObjective = median(objectiveDifference) <= 5;
    comparisonPassed = improvementMedian >= 20 || ...
        (equivalentObjective && reductionMedian >= 50);
    row = table(halfWidth,median(pso.Objective),median(hybrid.Objective), ...
        prctile(hybrid.Objective,25),prctile(hybrid.Objective,75), ...
        improvementMedian,prctile(objectiveImprovement,25), ...
        prctile(objectiveImprovement,75),median(pso.FunctionEvaluations), ...
        median(hybrid.FunctionEvaluations),reductionMedian,prctile(reduction,25), ...
        prctile(reduction,75),median(objectiveDifference),equivalentObjective, ...
        comparisonPassed,pValue, ...
        'VariableNames',{'HalfWidthDeg','PsoMedianObjective','HybridMedianObjective', ...
        'HybridObjectiveQ25','HybridObjectiveQ75','ObjectiveImprovementMedianPct', ...
        'ObjectiveImprovementQ25Pct','ObjectiveImprovementQ75Pct', ...
        'PsoMedianEvaluations','HybridMedianEvaluations', ...
        'EvaluationReductionMedianPct','EvaluationReductionQ25Pct', ...
        'EvaluationReductionQ75Pct','ObjectiveDifferenceMedianPct', ...
        'EquivalentObjectiveWithin5Pct','AlgorithmCriterionPassed', ...
        'PairedSignRankPValue'});
    metrics = [metrics;row]; %#ok<AGROW>
end
end
